// Diagnostics have fixed event names and no user-text arguments. Request replies
// use their own Print destination and never pass through this diagnostic channel.
#pragma once
#include <cstdint>
namespace diagnostics {
enum class Event : uint8_t {
  Power,
  Input,
  Pairing,
  PairingRequested,
  Link,
  Device,
  Settings,
  Mic,
  MicFailed,
  Prompt,
  PromptAnswered,
  Event,
  Reply,
  Mode,
  Display,
  Sound,
  SoundFailed,
  Ota,
  OtaFailed,
  OtaStarted,
  OtaDone,
  OtaCancelled,
  Face,
  FaceFailed,
  FaceInstall,
  Storage,
  StorageFailed,
  Network,
  NetworkFailed,
  Ir,
  IrFailed,
  Game,
  Launcher,
  Battery,
  Hid,
  HidInput,
  Suppressed,
  Count,
};
const char* message(Event event);
enum class Counter : uint8_t {
  ReplyBytes,
  AudioFrames,
  AudioDropped,
  AudioRetries,
  AudioPeak,
  ClipFrames,
  ClipExpectedFrames,
  StorageUsedKb,
  StorageTotalKb,
  StorageMountMs,
  FirmwareBytes,
  FirmwareOffset,
  FirmwareVerifyMs,
  FaceBytes,
  FaceMemoryKb,
  FaceLoadMs,
  FaceCount,
  FaceTier,
  FrameMicros,
  FrameRate,
};
const char* name(Counter counter);
}  // namespace diagnostics
