#!/usr/bin/env python3
"""Converts Inter (tools/fonts/Inter.ttf, OFL licence) into anti-aliased VLW
fonts for the stick, written to src/fonts_vlw.{h,cpp}.

Run after changing the sizes/characters below (needs Pillow):
    python3 tools/make_fonts.py

VLW layout (what LovyanGFX's VLWfont reads), all int32 big-endian:
  header  : glyph count, version (11), font size, 0, ascent, descent
  glyphs  : per glyph — unicode, height, width, xAdvance, dY (top above baseline), dX (left offset), 0
  bitmaps : per glyph, width*height bytes of 8-bit alpha, same order
"""
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).parent
TTF = HERE / "fonts" / "Inter.ttf"
OUT = HERE.parent / "src"

TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + "°’‘“”–—…•·×"
CLOCK = "0123456789:-–° "

# name, pixel size, weight (100-900), characters
FONTS = [
    ("INTER_10", 10, 450, TEXT),     # small print, hints
    ("INTER_12", 12, 420, TEXT),     # body
    ("INTER_14", 14, 500, TEXT),     # emphasised body, chips
    ("INTER_18", 18, 600, TEXT),     # titles
    ("INTER_24", 24, 500, TEXT),     # big words
    ("INTER_32", 32, 600, TEXT),     # bigger words (the Words face), semi-bold
    ("INTER_44", 44, 600, CLOCK),    # the clock (digits only), semi-bold
    ("INTER_56", 56, 600, CLOCK),    # the faces' landscape clock (digits only), semi-bold
    ("INTER_96", 96, 300, "0123456789: "),  # the dock clock (digits only), light
]


def glyph(font, ch):
    if ch == " ":
        return 0, 0, round(font.getlength(" ")), 0, 0, b""
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    adv = round(font.getlength(ch))
    if not w or not h:
        return 0, 0, adv, 0, 0, b""
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    return w, h, adv, -y0, x0, img.tobytes()


def vlw(size, weight, chars):
    font = ImageFont.truetype(str(TTF), size)
    font.set_variation_by_axes([min(32, max(14, size)), weight])
    ascent, descent = font.getmetrics()
    table, bitmaps = b"", b""
    chars = sorted(set(chars), key=ord)
    n = 0
    for ch in chars:
        w, h, adv, dy, dx, bmp = glyph(font, ch)
        table += struct.pack(">7i", ord(ch), h, w, adv, dy, dx, 0)
        bitmaps += bmp
        n += 1
    return struct.pack(">6i", n, 11, size, 0, ascent, descent) + table + bitmaps


def main():
    h = ["// Generated by tools/make_fonts.py from Inter (SIL Open Font License, tools/fonts/OFL.txt).",
         "// Anti-aliased VLW fonts; load with ui.cpp's font table.",
         "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
    c = ['#include "fonts_vlw.h"', ""]
    total = 0
    for name, size, weight, chars in FONTS:
        data = vlw(size, weight, chars)
        total += len(data)
        h.append(f"extern const uint8_t {name}[];  // {size} px, weight {weight}")
        h.append(f"extern const size_t  {name}_LEN;")
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
        c.append(f"const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};")
        c.append(f"const size_t {name}_LEN = {len(data)};\n")
        print(f"{name}: {len(data) / 1024:.1f} KB")
    (OUT / "fonts_vlw.h").write_text("\n".join(h) + "\n")
    (OUT / "fonts_vlw.cpp").write_text("\n".join(c))
    print(f"total {total / 1024:.1f} KB -> src/fonts_vlw.cpp")


if __name__ == "__main__":
    main()
